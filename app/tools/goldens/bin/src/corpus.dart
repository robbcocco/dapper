/// Strings drawn from a hostile alphabet with a fixed seed.
List<String> fuzzStrings(int count, {int salt = 0, int maxLen = 24}) {
  const alphabet = [
    'a', 'B', 'z', '0', '9', ' ', ' ', '.', '.', '-', '_', '/', '\\', ':', '*',
    '?', '"', '<', '>', '|', '\t', '\n', '\u0000', '\u007f', '…', '–', '—',
    'é', _nfdE, '漢', _emoji, 'İ', 'ẞ', 'Σ', '\u00a0', '\ufeff', '{', '}',
    'con', 'COM1', 'lpt9', '{track}', '{track:3}', '{disc:2}', '{year:4}',
    '{title}', '{album}', '{artist}', '{albumArtist}', '{bogus}',
  ];
  final rnd = seeded(salt);
  return [
    for (var i = 0; i < count; i++)
      [
        for (var j = rnd.nextInt(maxLen + 1); j > 0; j--)
          alphabet[rnd.nextInt(alphabet.length)]
      ].join(),
  ];
}

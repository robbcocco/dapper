#!/usr/bin/env bash
# Regenerates bin/copies/ copies of original Dart sources that the generator
# cannot import directly. Copies only rewrite imports (or extract a single
# top-level function verbatim) — logic is never altered. They live under bin/
# (file: URIs) rather than lib/ because package: libraries cannot use
# relative imports that reach outside the package, and the copies must keep
# importing the untouched originals in the repo's lib/.
#
#   bin/copies/extracted.dart  estimateTotalBytes (transfer_queue_notifier.dart,
#                              which pulls in Riverpod/Dio) and parseDfOutput
#                              (disk_space.dart, which pulls in win32/ffi).
#   bin/copies/windows/        path-dependent sources with `package:path`
#                              swapped for path_windows.dart (package:path's
#                              windows context), so Windows path output can
#                              be captured on any host.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(cd "$here/../../.." && pwd)"
src="$here/bin/copies"
win="$src/windows"
# Relative path from bin/copies/ and bin/copies/windows/ back to the repo's lib/.
from_src='../../../../../lib'
from_win='../../../../../../lib'

# Prints the top-level declaration whose first line starts with $2 through
# its closing `}` at column 0 (annotations such as @visibleForTesting are
# deliberately left out so the copy needs no package:meta import).
extract() {
  awk -v start="$2" '
    found == 0 && index($0, start) == 1 { found = 1 }
    found == 1 { print; if ($0 ~ /^}/) exit }
  ' "$1"
}

mkdir -p "$win"

{
  echo '// GENERATED by tools/goldens/sync.sh — verbatim extracts, do not edit.'
  echo "import '$from_src/domain/models/device_settings.dart';"
  echo "import '$from_src/domain/models/song.dart';"
  echo
  echo '// From lib/application/transfer/transfer_queue_notifier.dart'
  extract "$repo/lib/application/transfer/transfer_queue_notifier.dart" 'int estimateTotalBytes('
  echo
  echo '// From lib/platform/disk_space.dart'
  extract "$repo/lib/platform/disk_space.dart" 'int? parseDfOutput('
} > "$src/extracted.dart"

rewrite() {
  # $1 = source file, $2 = destination
  {
    echo '// GENERATED by tools/goldens/sync.sh — import-rewritten copy, do not edit.'
    sed \
      -e "s#^import 'package:path/path.dart' as p;#import '../path_windows.dart' as p;#" \
      -e "s#^import '../../core/#import '$from_win/core/#" \
      -e "s#^import '../../domain/models/device_settings.dart';#import 'device_settings.dart';#" \
      -e "s#^import '../../domain/#import '$from_win/domain/#" \
      -e "s#^import 'device_manifest.dart';#import '$from_win/application/transfer/device_manifest.dart';#" \
      "$1"
  } > "$2"
}

rewrite "$repo/lib/domain/models/device_settings.dart" "$win/device_settings.dart"
cp "$repo/lib/domain/models/device_settings.freezed.dart" "$win/device_settings.freezed.dart"
rewrite "$repo/lib/application/transfer/transfer_path_resolver.dart" "$win/transfer_path_resolver.dart"
rewrite "$repo/lib/application/transfer/playlist_sync_writer.dart" "$win/playlist_sync_writer.dart"

# Fail loudly if an import was missed (anything still pointing at the
# original tree's relative layout or at package:path).
if grep -nE "^import '(\.\./\.\./(core|domain|application|data)/|package:path/)" "$win"/*.dart; then
  echo 'sync.sh: unrewritten import above' >&2
  exit 1
fi
if ! grep -q 'int estimateTotalBytes(' "$src/extracted.dart" || ! grep -q 'int? parseDfOutput(' "$src/extracted.dart"; then
  echo 'sync.sh: extraction failed' >&2
  exit 1
fi
